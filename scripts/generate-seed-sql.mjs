#!/usr/bin/env node
// Generates supabase/seed/seed.sql from the two source JSON exports.
// Pure Node, no dependencies — this is deliberately runnable in environments
// with no npm registry access (it only needs `fs`/`path`).
//
// Usage:
//   node scripts/generate-seed-sql.mjs <finance-export.json> <shopping-export.json> [gowtham-email] [sanjana-email]
//
// Output: supabase/seed/seed.sql — paste into the Supabase SQL editor and
// run it AFTER 0001_schema.sql, 0002_rls.sql and 0003_auth_link.sql.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

const [, , financePath, shoppingPath, gowthamEmail, sanjanaEmail] = process.argv;

if (!financePath || !shoppingPath) {
  console.error(
    'Usage: node scripts/generate-seed-sql.mjs <finance-export.json> <shopping-export.json> [gowtham-email] [sanjana-email]'
  );
  process.exit(1);
}

const finance = JSON.parse(fs.readFileSync(financePath, 'utf8'));
const shopping = JSON.parse(fs.readFileSync(shoppingPath, 'utf8'));

const HOUSEHOLD_ID = 'hh_main';

// ---------------------------------------------------------------------------
// SQL literal helpers
// ---------------------------------------------------------------------------
function sqlStr(v) {
  if (v === null || v === undefined || v === '') return 'null';
  return `'${String(v).replace(/'/g, "''")}'`;
}
function sqlStrRequired(v) {
  return `'${String(v ?? '').replace(/'/g, "''")}'`;
}
function sqlNum(v) {
  if (v === null || v === undefined || v === '') return 'null';
  const n = Number(v);
  if (Number.isNaN(n)) return 'null';
  return String(n);
}
function sqlBool(v) {
  return v ? 'true' : 'false';
}
function sqlDate(v) {
  if (!v) return 'null';
  return `'${v}'`;
}
function sqlJson(v) {
  if (v === null || v === undefined) return "'[]'::jsonb";
  return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
}

const lines = [];
lines.push('-- Auto-generated by scripts/generate-seed-sql.mjs — do not hand-edit.');
lines.push('-- Run after 0001_schema.sql, 0002_rls.sql, 0003_auth_link.sql.');
lines.push('begin;');
lines.push('');

// ---------------------------------------------------------------------------
// households
// ---------------------------------------------------------------------------
lines.push('-- households');
lines.push(
  `insert into households (id, name, base_currency, exchange_rates) values (` +
    `${sqlStr(HOUSEHOLD_ID)}, 'Family', ${sqlStr(finance.baseCurrency || 'GBP')}, ${sqlJson(
      finance.exchangeRates
    )});`
);
lines.push('');

// ---------------------------------------------------------------------------
// members
// ---------------------------------------------------------------------------
lines.push('-- members');
const emailByMemberId = {
  m_gowtham: gowthamEmail || null,
  m_sanjana: sanjanaEmail || null,
};
for (const m of finance.members) {
  lines.push(
    `insert into members (id, household_id, email, name, role, color) values (` +
      `${sqlStr(m.id)}, ${sqlStr(HOUSEHOLD_ID)}, ${sqlStr(emailByMemberId[m.id])}, ` +
      `${sqlStrRequired(m.name)}, ${sqlStr(m.role)}, ${sqlStr(m.color)});`
  );
}
lines.push('');

// ---------------------------------------------------------------------------
// categories + subcategories
// ---------------------------------------------------------------------------
lines.push('-- categories');
let sort = 0;
for (const c of finance.categories) {
  lines.push(
    `insert into categories (id, household_id, name, icon, sort_order) values (` +
      `${sqlStr(c.id)}, ${sqlStr(HOUSEHOLD_ID)}, ${sqlStrRequired(c.name)}, ${sqlStr(
        c.icon
      )}, ${sort++});`
  );
}

// Some income transactions in the export use category ids that are literal
// names ("Salary", "Investment Income") rather than the "cat_xxx" ids in the
// categories list. We add real category rows for those two, and fold the
// literal "Other" straight into the existing cat_other row.
const categoryIdMap = {
  Salary: 'cat_salary',
  'Investment Income': 'cat_investment_income',
  Other: 'cat_other',
};
lines.push(
  `insert into categories (id, household_id, name, icon, sort_order) values (` +
    `'cat_salary', ${sqlStr(HOUSEHOLD_ID)}, 'Salary', 'Wallet', ${sort++});`
);
lines.push(
  `insert into categories (id, household_id, name, icon, sort_order) values (` +
    `'cat_investment_income', ${sqlStr(HOUSEHOLD_ID)}, 'Investment Income', 'TrendingUp', ${sort++});`
);
lines.push('');

lines.push('-- subcategories');
for (const c of finance.categories) {
  for (const s of c.subcategories || []) {
    lines.push(
      `insert into subcategories (id, category_id, name) values (` +
        `${sqlStr(s.id)}, ${sqlStr(c.id)}, ${sqlStrRequired(s.name)});`
    );
  }
}
lines.push('');

// ---------------------------------------------------------------------------
// accounts
// ---------------------------------------------------------------------------
lines.push('-- accounts');
const derivedRe = /derived|placeholder/i;
for (const a of finance.accounts) {
  lines.push(
    `insert into accounts (id, household_id, name, type, currency, balance, owner_id, country, notes, is_derived_placeholder) values (` +
      `${sqlStr(a.id)}, ${sqlStr(HOUSEHOLD_ID)}, ${sqlStrRequired(a.name)}, ${sqlStrRequired(
        a.type
      )}, ${sqlStrRequired(a.currency)}, ${sqlNum(a.balance)}, ${sqlStr(a.ownerId)}, ${sqlStr(
        a.country
      )}, ${sqlStr(a.notes)}, ${sqlBool(derivedRe.test(a.notes || ''))});`
  );
}
lines.push('');

// ---------------------------------------------------------------------------
// transactions
// ---------------------------------------------------------------------------
lines.push('-- transactions');
let remappedCategoryCount = 0;
for (const t of finance.transactions) {
  const categoryId = categoryIdMap[t.categoryId] ?? (t.categoryId || null);
  if (categoryIdMap[t.categoryId]) remappedCategoryCount++;
  lines.push(
    `insert into transactions (id, household_id, type, date, amount, currency, category_id, subcategory_id, description, person_id, entered_by_id, account_id, to_account_id, recurring, notes, country, items, created_at, updated_at, created_by, updated_by) values (` +
      `${sqlStr(t.id)}, ${sqlStr(HOUSEHOLD_ID)}, ${sqlStrRequired(t.type)}, ${sqlDate(
        t.date
      )}, ${sqlNum(t.amount)}, ${sqlStrRequired(t.currency)}, ${sqlStr(categoryId)}, ${sqlStr(
        t.subcategoryId
      )}, ${sqlStr(t.description)}, ${sqlStr(t.personId)}, ${sqlStr(t.enteredById)}, ${sqlStr(
        t.accountId
      )}, ${sqlStr(t.toAccountId)}, ${sqlBool(t.recurring)}, ${sqlStr(t.notes)}, ${sqlStr(
        t.country
      )}, ${t.items ? sqlJson(t.items) : 'null'}, ${
        t.createdAt ? `to_timestamp(${Number(t.createdAt)} / 1000.0)` : 'now()'
      }, ${t.updatedAt ? `to_timestamp(${Number(t.updatedAt)} / 1000.0)` : 'now()'}, ${sqlStr(
        t.createdBy
      )}, ${sqlStr(t.updatedBy)});`
  );
}
lines.push('');

// ---------------------------------------------------------------------------
// recurring_transactions
// ---------------------------------------------------------------------------
lines.push('-- recurring_transactions');
for (const r of finance.recurringTransactions) {
  lines.push(
    `insert into recurring_transactions (id, household_id, description, amount, currency, category_id, subcategory_id, frequency, account_id, person_id, active, type, notes, start_date, end_date) values (` +
      `${sqlStr(r.id)}, ${sqlStr(HOUSEHOLD_ID)}, ${sqlStrRequired(r.description)}, ${sqlNum(
        r.amount
      )}, ${sqlStrRequired(r.currency)}, ${sqlStr(r.categoryId)}, ${sqlStr(
        r.subcategoryId
      )}, ${sqlStrRequired(r.frequency)}, ${sqlStr(r.accountId)}, ${sqlStr(
        r.personId
      )}, ${sqlBool(r.active)}, ${sqlStrRequired(r.type)}, ${sqlStr(r.notes)}, ${sqlDate(
        r.startDate
      )}, ${sqlDate(r.endDate)});`
  );
}
lines.push('');

// ---------------------------------------------------------------------------
// assets
// ---------------------------------------------------------------------------
lines.push('-- assets');
for (const a of finance.assets) {
  lines.push(
    `insert into assets (id, household_id, name, type, owner_id, purchase_date, purchase_value, current_value, currency, country, notes, valuation_history) values (` +
      `${sqlStr(a.id)}, ${sqlStr(HOUSEHOLD_ID)}, ${sqlStrRequired(a.name)}, ${sqlStrRequired(
        a.type
      )}, ${sqlStr(a.ownerId)}, ${sqlDate(a.purchaseDate)}, ${sqlNum(a.purchaseValue)}, ${sqlNum(
        a.currentValue
      )}, ${sqlStrRequired(a.currency)}, ${sqlStr(a.country)}, ${sqlStr(a.notes)}, ${sqlJson(
        a.valuationHistory
      )});`
  );
}
lines.push('');

// ---------------------------------------------------------------------------
// investments
// ---------------------------------------------------------------------------
lines.push('-- investments');
for (const i of finance.investments) {
  lines.push(
    `insert into investments (id, household_id, type, name, provider, owner_id, currency, invested_amount, current_value, start_date, maturity_date, maturity_amount, premium_amount, premium_frequency, folio_number, notes) values (` +
      `${sqlStr(i.id)}, ${sqlStr(HOUSEHOLD_ID)}, ${sqlStrRequired(i.type)}, ${sqlStrRequired(
        i.name
      )}, ${sqlStr(i.provider)}, ${sqlStr(i.ownerId)}, ${sqlStrRequired(i.currency)}, ${sqlNum(
        i.investedAmount
      )}, ${sqlNum(i.currentValue)}, ${sqlDate(i.startDate)}, ${sqlDate(
        i.maturityDate
      )}, ${sqlNum(i.maturityAmount)}, ${sqlNum(i.premiumAmount)}, ${sqlStr(
        i.premiumFrequency
      )}, ${sqlStr(i.folioNumber)}, ${sqlStr(i.notes)});`
  );
}
lines.push('');

// ---------------------------------------------------------------------------
// liabilities
// ---------------------------------------------------------------------------
lines.push('-- liabilities');
const unconfirmedRe =
  /unconfirmed|please confirm|worth (checking|double-checking)|not matched|could overlap|not found in (either|any) statement/i;
for (const l of finance.liabilities) {
  lines.push(
    `insert into liabilities (id, household_id, name, type, original_amount, current_amount, currency, interest_rate, monthly_payment, start_date, expected_end_date, account_id, person_id, notes, is_unconfirmed) values (` +
      `${sqlStr(l.id)}, ${sqlStr(HOUSEHOLD_ID)}, ${sqlStrRequired(l.name)}, ${sqlStrRequired(
        l.type
      )}, ${sqlNum(l.originalAmount)}, ${sqlNum(l.currentAmount)}, ${sqlStrRequired(
        l.currency
      )}, ${sqlNum(l.interestRate)}, ${sqlNum(l.monthlyPayment)}, ${sqlDate(
        l.startDate
      )}, ${sqlDate(l.expectedEndDate)}, ${sqlStr(l.accountId)}, ${sqlStr(l.personId)}, ${sqlStr(
        l.notes
      )}, ${sqlBool(unconfirmedRe.test(l.notes || ''))});`
  );
}
lines.push('');

// ---------------------------------------------------------------------------
// goals
// ---------------------------------------------------------------------------
lines.push('-- goals');
for (const g of finance.goals) {
  lines.push(
    `insert into goals (id, household_id, name, description, target_amount, currency, target_date, current_amount, monthly_contribution, account_id, priority, owner_id, notes, contributions) values (` +
      `${sqlStr(g.id)}, ${sqlStr(HOUSEHOLD_ID)}, ${sqlStrRequired(g.name)}, ${sqlStr(
        g.description
      )}, ${sqlNum(g.targetAmount)}, ${sqlStrRequired(g.currency)}, ${sqlDate(
        g.targetDate
      )}, ${sqlNum(g.currentAmount)}, ${sqlNum(g.monthlyContribution)}, ${sqlStr(
        g.accountId
      )}, ${sqlStr(g.priority)}, ${sqlStr(g.ownerId)}, ${sqlStr(g.notes)}, ${sqlJson(
        g.contributions
      )});`
  );
}
lines.push('');

// ---------------------------------------------------------------------------
// budgets (none in current export, but handle if present)
// ---------------------------------------------------------------------------
if (finance.budgets?.length) {
  lines.push('-- budgets');
  for (const b of finance.budgets) {
    lines.push(
      `insert into budgets (id, household_id, category_id, person_id, amount, currency, period) values (` +
        `${sqlStr(b.id)}, ${sqlStr(HOUSEHOLD_ID)}, ${sqlStr(b.categoryId)}, ${sqlStr(
          b.personId
        )}, ${sqlNum(b.amount)}, ${sqlStrRequired(b.currency)}, ${sqlStrRequired(
          b.period || 'monthly'
        )});`
    );
  }
  lines.push('');
}

// ---------------------------------------------------------------------------
// finance-app shopping_list (top-level list, separate from companion app)
// ---------------------------------------------------------------------------
if (finance.shoppingList?.length) {
  lines.push('-- shopping_list (finance app quick list)');
  for (const s of finance.shoppingList) {
    lines.push(
      `insert into shopping_list (id, household_id, name, checked) values (` +
        `${sqlStr(s.id)}, ${sqlStr(HOUSEHOLD_ID)}, ${sqlStrRequired(s.name)}, ${sqlBool(
          s.checked
        )});`
    );
  }
  lines.push('');
}

// ---------------------------------------------------------------------------
// companion app: shopping_categories, shopping_trips, shopping_items
// ---------------------------------------------------------------------------
lines.push('-- shopping_categories (companion app)');
for (const c of shopping.categories) {
  lines.push(
    `insert into shopping_categories (id, household_id, name) values (` +
      `${sqlStr(c.id)}, ${sqlStr(HOUSEHOLD_ID)}, ${sqlStrRequired(c.name)});`
  );
}
lines.push('');

lines.push('-- shopping_trips');
for (const t of shopping.trips) {
  lines.push(
    `insert into shopping_trips (id, household_id, store, date, currency, notes, created_at) values (` +
      `${sqlStr(t.id)}, ${sqlStr(HOUSEHOLD_ID)}, ${sqlStrRequired(t.store)}, ${sqlDate(
        t.date
      )}, ${sqlStrRequired(t.currency)}, ${sqlStr(t.notes)}, ${
        t.createdAt ? `to_timestamp(${Number(t.createdAt)} / 1000.0)` : 'now()'
      });`
  );
}
lines.push('');

lines.push('-- shopping_items');
for (const i of shopping.items) {
  lines.push(
    `insert into shopping_items (id, trip_id, name, quantity, price, category_id) values (` +
      `${sqlStr(i.id)}, ${sqlStr(i.tripId)}, ${sqlStrRequired(i.name)}, ${sqlNum(
        i.quantity
      )}, ${sqlNum(i.price)}, ${sqlStr(i.categoryId)});`
  );
}
lines.push('');

if (shopping.shoppingList?.length) {
  lines.push('-- companion app shoppingList has entries but no dedicated table in schema yet');
}

lines.push('commit;');

const outDir = path.join(__dirname, '..', 'supabase', 'seed');
fs.mkdirSync(outDir, { recursive: true });
const outPath = path.join(outDir, 'seed.sql');
fs.writeFileSync(outPath, lines.join('\n') + '\n', 'utf8');

console.log(`Wrote ${outPath}`);
console.log(`  households: 1`);
console.log(`  members: ${finance.members.length}`);
console.log(`  categories: ${finance.categories.length + 2} (incl. Salary, Investment Income)`);
console.log(`  accounts: ${finance.accounts.length}`);
console.log(`  transactions: ${finance.transactions.length} (${remappedCategoryCount} category-id remapped)`);
console.log(`  recurring_transactions: ${finance.recurringTransactions.length}`);
console.log(`  assets: ${finance.assets.length}`);
console.log(`  investments: ${finance.investments.length}`);
console.log(`  liabilities: ${finance.liabilities.length}`);
console.log(`  goals: ${finance.goals.length}`);
console.log(`  shopping_categories: ${shopping.categories.length}`);
console.log(`  shopping_trips: ${shopping.trips.length}`);
console.log(`  shopping_items: ${shopping.items.length}`);
